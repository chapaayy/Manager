'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname,'..');
const read = p => fs.readFileSync(path.join(root,p),'utf8');
const js = read('manager/static/app.js');
const css = read('manager/static/app.css');
const html = read('manager/static/index.html');

new vm.Script(js);
assert.match(css,/--bg:#080809/,'black base theme must be explicit');
assert.match(css,/#hub-config-text\{display:block/,'editor must have full-size text area');
assert.match(html,/id="hub-config-editor"/);
assert.match(html,/id="hub-config-empty"/);
assert.match(html,/id="hub-config-text"/);
assert.match(html,/id="hub-config-import"/);
assert.match(html,/id="hub-config-save"/);
assert.match(html,/id="hub-config-apply"/);
assert.match(html,/\/assets\/app\.js\?v=1\.6\.1/);
assert.match(html,/\/assets\/app\.css\?v=1\.6\.1/);
assert.match(js,/const originalNodeList=loadNodes/,'cards should link to browser editor');
assert.match(js,/configFetchSerial/,'stale async results should not overwrite selection');
assert.match(js,/configDirty/,'unsaved modifications must be tracked');
assert.match(js,/waitNodeJob\(id,job\.id,100\)/,'first import should wait for remote read');
assert.match(js,/Сначала сохрани изменения в черновик/,'do not apply unsaved changes');
assert.match(js,/showPage=function\(page\)/,'warn before leaving unsaved editor');
console.log('PASS: black theme and browser configuration editor contracts');
